// =====================================================================================
//  THE CHAMBERS
//  Every room the dungeon can be built from. To make a new one, copy a chamber below,
//  give it a new name and change its tiles and spawns. The game checks your chamber when
//  it loads and explains in the browser console (F12) anything it can't use.
// =====================================================================================
//
//  name     A unique name for the chamber.
//
//  weight   How often it shows up compared to the others (optional, 1 if left out).
//           0.5 is half as often as 1.
//
//  tiles    The drawing of the chamber, one line per row. Each number is a tile:
//
//               0     floor
//               1     wall
//               3     stair: the player presses the interact key on it to go up a floor
//               null  nothing (void): nothing is built there and nobody can walk there
//
//           Any size works. The dungeon is a grid of blocks of 17 x 11 tiles, so the
//           chamber takes as many blocks as the drawing needs: 17 x 11 is one block,
//           34 x 11 two side by side, 34 x 22 a square of four, and so on. Leave a whole
//           block as null to make shapes like an L. A drawing that doesn't fill whole
//           blocks is completed with floor.
//
//  spawns   What appears in the chamber when the player walks in (optional):
//
//               { type: "enemy", x: 5, y: 3 }
//
//           x is the column and y the row, both counted from 0 at the top-left tile.
//           x: 5, y: 3 is the middle of that tile; decimals go in between, so x: 5.5
//           is right between columns 5 and 6.
//           Types: "enemy", "heart", "half heart", "chest", or a Prefab (for
//           programmers: import it and write type: MyPrefab). Spawns must stand on floor.
//           Enemies killed and items picked up stay gone when the player comes back.
//
//  Doors are added for you, in the middle of each side of every block (column 8, row 5
//  of the block), and so are the walls around the edge. Keep the doors' tiles as floor
//  (or wall, which gets replaced), never null, and keep two tiles inside each door free:
//  that's where the player appears.
//
//  floors   Which floors the chamber can appear on (optional), like floors: [2, 3].
//           The temple has FLOOR_COUNT floors (Config.js), from 1 at the bottom. Leave it
//           out and the chamber can appear on any floor. A floor always uses its own
//           chambers first: chambers without floors only fill in where none of that
//           floor's chambers of the same kind fit.
//
//  Optional, for special chambers:
//      kind   "start", "boss", "exit", or "treasure" (limited to a few per dungeon in
//             Config.js). Every floor needs a start and a boss chamber. Below the top
//             floor, the boss needs doors: "two doors", and an "exit" chamber goes right
//             behind it: one door (added for you) and a stair (3).
//      doors  "variants"  one copy of the chamber for every combination of doors
//                         (what one-block chambers get if left out)
//             "all"       a door on every side (what bigger chambers get if left out)
//             "dead ends" one copy per side, with only that door (exits get this)
//             "two doors" one copy per pair of sides (for bosses with an exit)
//
// =====================================================================================

